#pragma once

/// @file radio_busy.h
/// @brief Отметка «радио сейчас занято делом».
///
/// Прошивка иногда сама решает просканировать эфир — например, когда сигнал
/// текущей точки просел и надо посмотреть, нет ли точки получше. Скан
/// прерывает обмен на пару секунд, и если он придётся на обновление прошивки
/// или на отправку меню, работа сорвётся.
///
/// Поэтому куски кода, которым связь нужна целиком, обрамляют себя
/// RadioBusyGuard, а сканирование ждёт, пока занятость снимется. Это отметка о
/// намерении, а не блокировка: ничего не запрещается, спрашивающий сам решает,
/// что делать.
///
/// Счётчик, а не флаг: участки вкладываются друг в друга (OTA внутри которого
/// публикуется статус), и выход из внутреннего не должен снимать отметку,
/// поставленную внешним.

#include <stdint.h>

namespace idryer {

/// @brief Радио занято — начало участка.
void radioBusyBegin();
/// @brief Радио занято — конец участка.
void radioBusyEnd();
/// @brief Сейчас идёт хотя бы один такой участок.
bool radioBusy();

/// @brief Отмечает занятость на время жизни объекта.
struct RadioBusyGuard {
    RadioBusyGuard()  { radioBusyBegin(); }
    ~RadioBusyGuard() { radioBusyEnd(); }
    RadioBusyGuard(const RadioBusyGuard&)            = delete;
    RadioBusyGuard& operator=(const RadioBusyGuard&) = delete;
};

} // namespace idryer
